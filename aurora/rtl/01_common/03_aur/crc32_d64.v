`timescale 1ns / 1ps

module crc32_d64 (
    input      [                          31:0] i_032_crc                                       , // crc in
    input      [                          63:0] i_064_data                                      , // data, byte0 = [7:0]
    output     [                          31:0] o_032_crc                                         // crc out
);

    // ********************************************************************************************
    // localparameter declare
    // ********************************************************************************************

    // =============================================================================
    // internal signal define
    // =============================================================================

    wire       [                          31:0] w_032_c0                                        ;
    wire       [                          31:0] w_032_c1                                        ;
    wire       [                          31:0] w_032_c2                                        ;
    wire       [                          31:0] w_032_c3                                        ;
    wire       [                          31:0] w_032_c4                                        ;
    wire       [                          31:0] w_032_c5                                        ;
    wire       [                          31:0] w_032_c6                                        ;
    wire       [                          31:0] w_032_c7                                        ;

    // =================================================================================================
    // RTL Body
    // =================================================================================================

    assign w_032_c0                             = f_crc8(i_032_crc, i_064_data[ 7: 0])          ;
    assign w_032_c1                             = f_crc8(w_032_c0 , i_064_data[15: 8])          ;
    assign w_032_c2                             = f_crc8(w_032_c1 , i_064_data[23:16])          ;
    assign w_032_c3                             = f_crc8(w_032_c2 , i_064_data[31:24])          ;
    assign w_032_c4                             = f_crc8(w_032_c3 , i_064_data[39:32])          ;
    assign w_032_c5                             = f_crc8(w_032_c4 , i_064_data[47:40])          ;
    assign w_032_c6                             = f_crc8(w_032_c5 , i_064_data[55:48])          ;
    assign w_032_c7                             = f_crc8(w_032_c6 , i_064_data[63:56])          ;

    assign o_032_crc                            = w_032_c7                                      ;

    function [31:0] f_crc8;
        input [31:0] i_crc;
        input [ 7:0] i_dat;
        integer      k;
        reg   [31:0] r_c;
        begin
            r_c                                 = i_crc                                         ;
            for (k = 0; k < 8; k = k + 1) begin
                if (r_c[0] ^ i_dat[k])
                    r_c                         = (r_c >> 1) ^ 32'hedb8_8320                    ;
                else
                    r_c                         = (r_c >> 1)                                    ;
            end
            f_crc8                              = r_c                                           ;
        end
    endfunction

endmodule
